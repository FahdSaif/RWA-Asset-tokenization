"""
Layer 1 — Investor Eligibility Evaluation Agent (paper Sec. V-C,
"Investor Eligibility Evaluation Agent").

Per the paper: "Evaluation inputs are drawn from the zero-knowledge proof
attestations generated by the Verification and Identity Layer, which
confirm relevant credential attributes without revealing underlying
personal data." This agent therefore never sees a raw jurisdiction,
net-worth figure, or accreditation document — only the boolean outcome
of verifying a submitted ZK membership proof against a public
allow-list, plus a verified Verifiable Credential's *typed* claim (e.g.
`accredited: True`) where the predicate does not require hiding the
value itself.

The output is a structured, binary eligibility determination with an
explanatory reasoning trace identifying exactly which predicates were
evaluated — issued as a CRR that the Transaction Validation Module
(Layer 3) can later cite via the `require_eligibility_crr` rule type.
"""
from __future__ import annotations

from typing import List, Optional, Sequence

from arca.layer1_intelligence.crr import ComplianceRecommendationRecord, issue_crr
from arca.layer2_identity.did_registry import DIDKeyPair
from arca.layer2_identity.verifiable_credentials import (
    CredentialRevocationRegistry,
    VerifiableCredential,
    verify_credential,
)
from arca.layer2_identity.zkp_module import ORMembershipProof, verify_membership


class InvestorEligibilityEvaluationAgent:
    def __init__(self, keypair: DIDKeyPair, revocation_registry: CredentialRevocationRegistry):
        self.keypair = keypair
        self.revocation_registry = revocation_registry

    def evaluate(
        self,
        tx_id: str,
        jurisdiction_proof: Optional[ORMembershipProof],
        allowed_jurisdictions_encoded: Sequence[int],
        accreditation_credential: Optional[VerifiableCredential],
        require_accreditation: bool,
    ) -> ComplianceRecommendationRecord:
        reasoning: List[str] = []
        checks_passed = True

        if jurisdiction_proof is None:
            reasoning.append("No jurisdiction-allowlist ZK proof was submitted.")
            checks_passed = False
        else:
            jurisdiction_ok = verify_membership(jurisdiction_proof, list(allowed_jurisdictions_encoded))
            reasoning.append(
                "Jurisdiction-allowlist ZK proof " + ("verified against the current allow-list." if jurisdiction_ok
                else "FAILED verification against the current allow-list.")
            )
            checks_passed = checks_passed and jurisdiction_ok

        if require_accreditation:
            if accreditation_credential is None:
                reasoning.append("Accreditation required but no credential was presented.")
                checks_passed = False
            else:
                cred_ok = verify_credential(accreditation_credential, self.revocation_registry)
                accredited_claim = bool(accreditation_credential.claims.get("accredited", False))
                reasoning.append(
                    f"Accreditation credential signature/validity check: {'passed' if cred_ok else 'FAILED'}; "
                    f"claimed accredited={accredited_claim}."
                )
                checks_passed = checks_passed and cred_ok and accredited_claim
        else:
            reasoning.append("Accreditation not required for this asset class / jurisdiction combination.")

        return issue_crr(
            self.keypair,
            determination_type="eligibility",
            context_id=tx_id,
            outcome=checks_passed,
            reasoning_trace=reasoning,
            inputs={
                "require_accreditation": require_accreditation,
                "jurisdiction_proof_present": jurisdiction_proof is not None,
                "accreditation_credential_present": accreditation_credential is not None,
            },
        )
